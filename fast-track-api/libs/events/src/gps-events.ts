/**
 * GPS event contract (docs/spec.md section 3 `GpsPoint`, section 5.4
 * `GpsBatchReceived`, `LocationUpdated`, `DriverNearDestination`).
 *
 * Shared by the GPS Ingestion API (producer of `gps.batches`), the GPS
 * Tracking Worker (consumer of `gps.batches`, producer of
 * `tracking.locations` and `tracking.proximity`) and their consumers, so
 * every side agrees on the shape of these messages.
 */

/** Spec 3 `PointBatch`: a batch holds between 1 and 50 points. */
export const GPS_BATCH_MIN_POINTS = 1;
export const GPS_BATCH_MAX_POINTS = 50;

/** One GPS reading taken by the driver's device (spec 3, `GpsPoint`). */
export interface GpsPoint {
  /** Latitude, WGS-84, in [-90, 90]. */
  lat: number;
  /** Longitude, WGS-84, in [-180, 180]. */
  lng: number;
  /** ISO-8601 UTC time measured by the device, not by the server. */
  deviceTime: string;
  /** Monotonic per driver device, >= 0. The worker orders and deduplicates by it. */
  sequence: number;
  /** Optional GPS accuracy, >= 0. */
  accuracyMeters?: number;
  /** Optional speed, >= 0. */
  speedKmh?: number;
}

/** `eventType` of the event published to `gps.batches`. */
export const GPS_BATCH_RECEIVED = 'GpsBatchReceived';

/** Current `schemaVersion` of {@link GpsBatchReceivedPayload}. */
export const GPS_BATCH_RECEIVED_SCHEMA_VERSION = 1;

/** Payload of `GpsBatchReceived` (spec 5.4). Kafka key = `driverId`. */
export interface GpsBatchReceivedPayload {
  /** Driver that sent the batch; taken from the JWT `sub`, never from the body. */
  driverId: string;
  /** Generated by the API; returned to the app in the 202 response. */
  batchId: string;
  /** ISO-8601 UTC time when the API received the batch. */
  receivedAt: string;
  /** 1–50 points, in the order the app sent them (the worker sorts them). */
  points: GpsPoint[];
}

/** A WGS-84 position (spec 3 `Location`). */
export interface GeoLocation {
  lat: number;
  lng: number;
}

/** `eventType` of the event published to `tracking.locations`. */
export const LOCATION_UPDATED = 'LocationUpdated';

/** Current `schemaVersion` of {@link LocationUpdatedPayload}. */
export const LOCATION_UPDATED_SCHEMA_VERSION = 1;

/**
 * Payload of `LocationUpdated` (spec 5.4). Kafka key = `orderId`.
 * One event per in-progress order of the driver and processed batch, carrying
 * the point with the highest sequence (the new last known location).
 */
export interface LocationUpdatedPayload {
  orderId: string;
  driverId: string;
  location: GeoLocation;
  /** ISO-8601 UTC device time of the point. */
  deviceTime: string;
  /** Consumers apply the event only if it is higher than the one they stored. */
  sequence: number;
}

/** `eventType` of the event published to `tracking.proximity`. */
export const DRIVER_NEAR_DESTINATION = 'DriverNearDestination';

/** Current `schemaVersion` of {@link DriverNearDestinationPayload}. */
export const DRIVER_NEAR_DESTINATION_SCHEMA_VERSION = 1;

/** Why NEARBY fired: straight-line distance < 500 m, or ETA < 300 s (spec 5.4). */
export type ProximityTrigger = 'DISTANCE' | 'ETA';

/** Payload of `DriverNearDestination` (spec 5.4). Kafka key = `orderId`. Emitted at most once per order. */
export interface DriverNearDestinationPayload {
  orderId: string;
  driverId: string;
  trigger: ProximityTrigger;
  /** Straight-line distance to the destination, rounded to metres. */
  distanceMeters: number;
  /** ETA from the Maps/ETA provider; null when it was not consulted or failed (ADR-013). */
  etaSeconds: number | null;
  location: GeoLocation;
  /** ISO-8601 UTC time when the worker detected it. */
  detectedAt: string;
}
