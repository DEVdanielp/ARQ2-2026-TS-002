/**
 * EventEnvelope: the common "wrapper" around every event FastTrack publishes.
 *
 * Why it exists
 * -------------
 * Kafka only moves bytes; it does not know what an event is. If every service
 * invented its own message shape, every consumer would need custom parsing and
 * we could not build shared infrastructure (idempotency, tracing, DLQ tooling).
 * The spec (docs/spec.md, section 3 `EventEnvelope`) therefore fixes one shape
 * for every message value on every topic (spec 5.1): a set of metadata fields
 * that all events share, plus a `payload` with the event-specific data.
 *
 * What each field is for
 * ----------------------
 * - eventId:          unique id of this event. Consumers store it to detect
 *                     redeliveries and skip duplicates (ADR-009).
 * - eventType:        name of the fact, e.g. "OrderDelivered". Consumers switch
 *                     on it. Also copied into the Kafka header `eventType`.
 * - schemaVersion:    version of the payload shape. Additive changes keep it;
 *                     breaking changes increase it (spec 5.2, schema evolution).
 * - occurredAt:       when the fact happened, ISO-8601 in UTC (spec 2, Time).
 * - producer:         name of the service that published it.
 * - correlationId:    id of the original HTTP request (added by Kong), so logs
 *                     and traces of one user action can be followed across
 *                     services (spec 2, Correlation).
 * - aggregateId:      the entity the event is about (orderId, driverId or
 *                     customerId). Usually also the Kafka key.
 * - aggregateVersion: the order's version for order events, so consumers can
 *                     ignore stale events that arrive late (ADR-009, ADR-010).
 *                     `null` when the event has no versioned aggregate.
 * - payload:          the event-specific data (see spec 5.4, event catalog).
 */
import { randomUUID } from 'node:crypto';

/**
 * Shape of every event value published to Kafka (docs/spec.md section 3).
 *
 * @typeParam TPayload - type of the event-specific `payload`. Defaults to
 *   `unknown` so code that does not know the event type is forced to narrow it.
 */
export interface EventEnvelope<TPayload = unknown> {
  /** UUID v4, unique per event; used for idempotency. */
  eventId: string;
  /** Event name, e.g. `GpsBatchReceived`. */
  eventType: string;
  /** Version of the payload schema (integer, starts at 1). */
  schemaVersion: number;
  /** ISO-8601 UTC timestamp of when the fact happened. */
  occurredAt: string;
  /** Name of the publishing service, e.g. `orders-service`. */
  producer: string;
  /** Correlation id propagated from the original request (UUID). */
  correlationId: string;
  /** orderId, driverId or customerId (UUID). */
  aggregateId: string;
  /** Aggregate version for order events; `null` otherwise. Optional in the spec. */
  aggregateVersion?: number | null;
  /** Event-specific data. */
  payload: TPayload;
}

/**
 * Fields the publisher must provide when creating an envelope.
 * `eventId` and `occurredAt` are generated by {@link createEnvelope}.
 */
export type CreateEnvelopeInput<TPayload> = Omit<
  EventEnvelope<TPayload>,
  'eventId' | 'occurredAt'
>;

/**
 * Builds a new {@link EventEnvelope}, generating `eventId` (random UUID v4)
 * and `occurredAt` (now, ISO-8601 UTC).
 *
 * Call it ONCE per fact, at the moment the fact happens. If the event is later
 * re-sent (for example by the outbox relay after a crash, ADR-005), the SAME
 * envelope must be re-sent, not a new one: keeping the same `eventId` is what
 * lets consumers recognise the duplicate (ADR-009).
 *
 * @example
 * const envelope = createEnvelope({
 *   eventType: 'GpsBatchReceived',
 *   schemaVersion: 1,
 *   producer: 'gps-ingestion-api',
 *   correlationId,
 *   aggregateId: driverId,
 *   aggregateVersion: null,
 *   payload: { driverId, batchId, receivedAt, points },
 * });
 */
export function createEnvelope<TPayload>(
  input: CreateEnvelopeInput<TPayload>,
): EventEnvelope<TPayload> {
  return {
    eventId: randomUUID(),
    eventType: input.eventType,
    schemaVersion: input.schemaVersion,
    // toISOString() always returns UTC with a trailing "Z".
    occurredAt: new Date().toISOString(),
    producer: input.producer,
    correlationId: input.correlationId,
    aggregateId: input.aggregateId,
    // Normalise "not provided" to null so the JSON always has the field.
    aggregateVersion: input.aggregateVersion ?? null,
    payload: input.payload,
  };
}

/**
 * Thrown by {@link parseEnvelope} when a Kafka message value is not a valid
 * envelope. Retrying cannot fix this kind of error, so consumers send such
 * messages straight to the DLQ (ADR-012).
 */
export class InvalidEnvelopeError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'InvalidEnvelopeError';
  }
}

/** Fields the spec marks as required, with the JS type each one must have. */
const REQUIRED_FIELDS: ReadonlyArray<[keyof EventEnvelope, string]> = [
  ['eventId', 'string'],
  ['eventType', 'string'],
  ['schemaVersion', 'number'],
  ['occurredAt', 'string'],
  ['producer', 'string'],
  ['correlationId', 'string'],
  ['aggregateId', 'string'],
];

/**
 * Parses a raw Kafka message value (JSON text) into an {@link EventEnvelope}.
 *
 * It checks that the text is JSON and that the required metadata fields exist
 * with the right type. It does NOT validate the `payload`: each consumer knows
 * its own event types and validates the payload it cares about.
 *
 * @param raw - the message value as text, or `null` (a "tombstone" message).
 * @throws {InvalidEnvelopeError} if the value is empty, not JSON, or not an envelope.
 */
export function parseEnvelope<TPayload = unknown>(
  raw: string | null,
): EventEnvelope<TPayload> {
  if (raw === null || raw.length === 0) {
    throw new InvalidEnvelopeError('Message value is empty');
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    throw new InvalidEnvelopeError(
      `Message value is not valid JSON: ${(error as Error).message}`,
    );
  }

  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    throw new InvalidEnvelopeError('Message value is not a JSON object');
  }

  const candidate = parsed as Record<string, unknown>;
  for (const [field, type] of REQUIRED_FIELDS) {
    if (typeof candidate[field] !== type) {
      throw new InvalidEnvelopeError(
        `Envelope field "${field}" is missing or is not a ${type}`,
      );
    }
  }
  if (!('payload' in candidate)) {
    throw new InvalidEnvelopeError('Envelope field "payload" is missing');
  }

  return candidate as unknown as EventEnvelope<TPayload>;
}
